// BlockHashCheckpoint returns the expected block hash, if one is hardcoded for
// this chain and height. Returned hashes are values; callers cannot mutate the table.
func BlockHashCheckpoint(chainID *big.Int, number uint64) (common.Hash, bool) {
	if chainID == nil || chainID.Cmp(MetisMainnetChainID) != 0 || number > AndromedaLastCheckpoint || number%AndromedaCheckpointInterval != 0 {
		return common.Hash{}, false
	}
	return andromedaBlockHashes[number/AndromedaCheckpointInterval], true
}
